/** 説明の 一覧 → えらんだ 説明を ふだんの 窓で 1窓ずつ（ui/explain.ts）。 */
const openGuides = async (
	ctx: Ctx,
	title: string,
	guides: { label: string; pages: readonly string[]; guide?: Guide }[],
): Promise<void> => {
	let start = 0;
	for (;;) {
		const v = await listWindow(
			ctx,
			title,
			guides.map((g, i) => ({ label: g.label, value: String(i) })),
			{ start },
		);
		if (v === null) return;
		start = Number(v);
		const g = guides[start];
		if (!g) continue;
		// 項目の ある 説明は もう 1段 えらぶ（読みたい ところだけ）
		if (g.guide && g.guide.pages.length > 1)
			await openTopics(ctx, g.label, g.guide);
		else await explain(ctx, [...g.pages]);
	}
};

const openTopics = async (
	ctx: Ctx,
	title: string,
	guide: Guide,
): Promise<void> => {
	let start = 0;
	for (;;) {
		const v = await listWindow(
			ctx,
			title,
			guide.pages.map((_, i) => ({
				label: guide.topics[i] ?? "",
				value: String(i),
			})),
			{ start },
		);
		if (v === null) return;
		start = Number(v);
		const pages = guide.pages[start];
		if (pages) await explain(ctx, [...pages]);
	}
};

export const openHowto = async (ctx: Ctx): Promise<void> => {
	let start = 0;
	for (;;) {
		const v = await listWindow(
			ctx,
			"あそびかた",
			[
				...PAGES.map((p) => ({ label: p.label, sub: p.sub, value: p.value })),
				// 2ch の ことば（ダンジョンの 中からも 引けるように。村では 集会所の 本棚にも ある）
				{ label: "ことば", sub: "2ch・おんJのことば", value: "words" },
				// 決まりの むずかしい ゲームと 町の しくみ（data/arcade/guides.ts・data/town/guides.ts）
				{
					label: "ゲームの決まり",
					sub: "こいこい・カジノほか",
					value: "games",
				},
				{
					label: "町のしくみ",
					sub: "お金・倉庫・家・なかよし",
					value: "town",
				},
			],
			{ start },
		);
		if (v === null) return;
		if (v === "words") {
			start = PAGES.length;
			await openGlossary(ctx);
			continue;
		}
		if (v === "games" || v === "town") {
			start = PAGES.length + (v === "games" ? 1 : 2);
			await openGuides(
				ctx,
				v === "games" ? "ゲームの決まり" : "町のしくみ",
				v === "games" ? GAME_GUIDES() : TOWN_GUIDES(),
			);
			continue;
		}
		const i = PAGES.findIndex((p) => p.value === v);
		const page = PAGES[i];
		if (!page) return;
		start = i;
		await infoWindow(ctx, page.label, page.html, { cls: "howto" });
	}
};
