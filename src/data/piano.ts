/** 音名 → ドからの 半音。 */
const SOLFEGE: Record<string, number> = {
	ド: 0,
	レ: 2,
	ミ: 4,
	ファ: 5,
	ソ: 7,
	ラ: 9,
	シ: 11,
};

/** ガイドの 旋律（鍵盤の 番号 0〜11 の 列）。知らない 字は とばす。 */
export const guideKeys = (notes: string): number[] =>
	notes
		.split(/\s+/)
		.filter((t) => t in SOLFEGE)
		.map((t) => SOLFEGE[t]);

