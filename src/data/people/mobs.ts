/** 村で 口を きく だれか（仲間か、ほかの子）。 */
export type Cast = Speaker | MobId;

/**
 * 窓の 前の 小さな しぐさ（窓には 数えない。なくても 話は 通じる）。
 * turn は その場で 向きだけ かえる（U・D・L・R と 待ちの w。s.move）。face は 向く（s.face）。
 * walk は 家（spot）の まわり 2マスの 中へ 歩く（人と キリコを よける。行けなければ 何もしない。s.goto）。
 */
export type Beat =
	| { k: "turn"; route: string }
	| { k: "face"; to: Dir | "player" }
	| { k: "walk"; to: readonly [number, number]; face?: Dir };

/**
 * 1窓。who が "mob" なら その子、"kiriko" なら キリコ、null なら 地の文、
 * 仲間・ほかの子なら 近くに いるときだけ。need も 同じ。
 */
export type MobLine = Cue & {
	who: "mob" | "kiriko" | Cast | null;
	text: string;
	need?: Cast;
	beat?: Beat;
};

/**
 * 節目（持ち帰った ダンジョン・もぐった回数）。shallow は 段0から いる ぷゆゆ と 原住民 だけ。
 */
export type Milestone = "shallow" | "main" | "deep" | "runs10";

/** 話を えらぶ 手がかり（ui/village/villageMobs.ts が 保存と 端末の 日付から 作る。data は 保存を 読まない）。 */
export type MobCtx = {
	/** 前の冒険（まだ 無ければ null）。cause は「〜に　たおされた」など。 */
	last: {
		kind: "dead" | "clear" | "escape";
		cause: string;
		depth: number;
		/** 持ち帰る 途中だった。 */
		returning: boolean;
		/** 下りの 板の 奥（7割から）まで 行った（「深くまで」の ひとこと）。 */
		far?: boolean;
	} | null;
	/** 図鑑で 会った 敵（id。ぷゆゆは 前の 名前の まま "tousuko"、メタルぷゆゆは "metal"）。 */
	seen: readonly string[];
	/** 会った子。 */
	met: readonly MobId[];
	/** 見た 話（`<id>:<key>`。節目は `<id>:@<節目>`）。 */
	talked: readonly string[];
	today: Today;
};

export type MobChat = {
	key: string;
	/** その人・その子が 近くに いるときだけ。 */
	with?: Cast;
	/** 合う 帰りにだけ 選ばれる。 */
	when?: (x: MobCtx) => boolean;
	/** 前の冒険への 反応を かねる（聞いた 帰りは 反応を 出さない）。 */
	answersRun?: boolean;
	lines: MobLine[];
};

export type MobDef = {
	name: string;
	/** 歩行グラ（RPGEN 形式）。 */
	sprite: string;
	spot: readonly [number, number];
	dir: Dir;
	/** 家の まわり 2マスを うろうろ する。 */
	wander?: boolean;
	/**
	 * 立ち絵（public/ からの パス。まだ 描いていなければ 「立ち絵（仮）」の ダミーが 出る。ART_TODO.md）。
	 * 人の 子（リノ・アル）だけ。マスコット（ぷゆゆ・おんJwiki の 顔文字の マイナーズ）は やきうと 同じく 立ち絵なし。
	 */
	portrait?: string;
	/** 名前欄に 出す 名前（無ければ name。解音ゼロの サブ機は 型番つき）。 */
	label?: string;
	/** 名前欄の 色を かりる 仲間（立ち絵は かりない）。ぷゆゆは やきう（rpg と 同じ）。 */
	voice?: Speaker;
	/** 名前欄の 色（その子 だけの 色。voice より 先）。読み上げの 声は data/people/cast.ts の MOB_VOICE。 */
	color?: string;
	/** 人気投票の はり紙に 載らない（殿堂入りの おんちゃん・マイナーズでは ない ぷゆゆ）。 */
	noVote?: boolean;
	meet: MobLine[];
	/** はじめましての あと、書きこむまで 毎回 きく（おんすちゃん）。 */
	ask?: {
		lines: MobLine[];
		options: readonly [string, string];
		yes: MobLine[];
		no: MobLine[];
	};
	milestones: Partial<Record<Milestone, MobLine[]>>;
	chats: MobChat[];
	season: Partial<Record<Season, string>>;
	/**
	 * 前の冒険への 反応（1回の 帰りに 1回。starve は おなかが すいて たおれたとき）。
	 * by は たおれたときの 条件つき（上から 見て 最初に 合った もの。starve・深さより 先）。
	 */
	react: {
		dead: string;
		deep: string;
		clear: string;
		escape: string;
		starve?: string;
		by?: readonly { when: (x: MobCtx) => boolean; text: string }[];
	};
	/** いつもの ひとこと（7つなら 曜日で。日曜 はじまり）。 */
	idle: string | readonly string[];
	/** 人気投票の はり紙で 1票 入れてもらったとき（1回だけ）。 */
	thx: MobLine[];
};

const m = (text: string, need?: Cast): MobLine => ({
	who: "mob",
	text,
	need,
});
const n = (text: string, need?: Cast): MobLine => ({
	who: null,
	text,
	need,
});
/** キリコの 1窓（雑談だけ）。 */
const k = (text: string): MobLine => ({ who: "kiriko", text });
/** 仲間か ほかの子の 1窓（近くに いるときだけ）。 */
const c = (who: Cast, text: string): MobLine => ({ who, text });
/** 窓の 前に しぐさを つける。 */
const b = (beat: Beat, line: MobLine): MobLine => ({ ...line, beat });
/** 窓に 感情の 記号・体の 動きを つける（engine/emote.ts。話す 人が 同じ マップに いるときだけ 出る）。 */
const e = (cue: Cue, line: MobLine): MobLine => ({ ...line, ...cue });

