/** 1窓。me ＝ その 人、kiriko ＝ キリコの 声、null ＝ 地の文。感情の 記号・体の 動き（Cue）も つけられる。 */
export type BondLine = Cue & { who: "me" | "kiriko" | null; text: string };

/** もらった 物（家の 収納の「もらった　物」）。 */
export type Keepsake = {
	id: string;
	name: string;
	/** わたす ときの ひとこと（その 人の 声）。 */
	say: string;
	/** 一覧で 選んだ ときの 文（地の文）。 */
	desc: string;
};

export type BondDef = {
	/** 誕生日（月・日）。 */
	birthday: readonly [number, number];
	love: readonly GiftId[];
	like: readonly GiftTag[];
	hate?: readonly GiftTag[];
	react: Record<GiftTaste | "bday", string>;
	/** なかよしの 話（♥3・♥5）。 */
	scenes?: readonly [readonly BondLine[], readonly BondLine[]];
	/** いつもの ひとこと（♥2〜3・♥4〜5）。 */
	warm?: readonly [string, string];
	/** 季節の プレゼントを わたす ときの ひとこと（無ければ 地の文だけ）。 */
	season?: Partial<Record<Season, string>>;
};

const me = (text: string): BondLine => ({ who: "me", text });
const k = (text: string): BondLine => ({ who: "kiriko", text });
const n = (text: string): BondLine => ({ who: null, text });
/** 窓に 感情の 記号・体の 動きを つける（engine/emote.ts）。 */
const e = (cue: Cue, line: BondLine): BondLine => ({ ...line, ...cue });

