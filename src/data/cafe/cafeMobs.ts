// - hello：話しかけた ときの ひとこと（1窓）。
// - talks：「話す」で 上から 順に 1本ずつ（見た 話は くり返さない。1回の 帰りに 1人 1本）。ぜんぶ 見たら idle。
//   with は その人・その子が 店に いる とき だけ（仲間も 住人も、その帰りに 店に 来ている とき）。
// - treat：一杯 おごられた ときの ひとこと（{drink} は 一杯の 名前）。sip：ひとくち 飲んだ あとの 感想。
// 決まりは 村の 住人の 話と 同じ（data/people/mobs.ts の 先頭）：1行は 全角22字・2行まで、1本は 1〜3窓（口出し こみで 4窓まで）、
// キリコの しぐさは 地の文、返事は k（吾輩・ンゴ）。who の "mob" は その子、null は 地の文、仲間・ほかの子は その人。
// 店の 小物（data/town/rooms.ts）：鳴らない 鍵盤が ひとつの ピアノ・0時で 止まった 柱時計・棚の 奥の『Part1』の 瓶・
// にぎやかだった ころの おんJの スレの 絵。マスター（白ひげ。「〜ですぞ」）は 地の文の 中だけで 出る。

