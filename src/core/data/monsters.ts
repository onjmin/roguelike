/** その階に出るモンスター（板だけの 敵は その板でだけ。ボスは 出ない）。 */
export const monstersFor = (depth: number, dungeon?: DungeonId): MonsterDef[] =>
	M.filter(
		(m) =>
			!m.boss &&
			!m.hunter &&
			depth >= m.floors[0] &&
			depth <= m.floors[1] &&
			(!m.board || m.board === dungeon),
	);

